import { z } from "zod";
import { getConfig } from "../config.js";
import { JevValidationError } from "../errors.js";
import { toolRouteQuestions } from "../packs/tool-route.js";
import { distributionSupportsConfidence, validatePolicyThresholds, type PolicyAction } from "../policy.js";
import { asChoice, asNoul } from "../result.js";
import { systemOne, withToolContext, type ToolContext } from "../typesafe.js";

// Zod records intentionally strip __proto__. Reject it before any parsing can
// silently change a call that the host already validated and authorized.
const unchangedJson = z.unknown().superRefine((value, context) => {
  const pending = [value];
  const seen = new Set<object>();
  while (pending.length) {
    const item = pending.pop();
    if (!item || typeof item !== "object" || seen.has(item)) continue;
    seen.add(item);
    if (Object.hasOwn(item, "__proto__")) {
      context.addIssue({ code: "custom", message: "Tool arguments must not contain __proto__ keys; the JSON validator cannot preserve them." });
      return;
    }
    for (const child of Object.values(item)) pending.push(child);
  }
});
export const argumentsSchema = z.intersection(unchangedJson, z.record(z.string(), z.json()));
export const toolCandidateSchema = z.object({
  id: z.string().min(1),
  name: z.string().min(1).refine(name => name.trim().length > 0, "Tool name must not be blank").describe("Exact tool name from the host's available tool registry"),
  arguments: argumentsSchema.describe("Complete JSON arguments prepared by host code or an existing plan; never generated by Jev"),
  description: z.string().min(1).describe("Purpose of this exact call"),
  effect: z.enum(["read_only", "local_write", "external_write", "destructive", "unknown"]),
  authorized: z.boolean().optional().describe("Trusted host fact: the existing user authorization covers this exact call"),
  schema_valid: z.boolean().optional().describe("Trusted host fact: arguments validated against the actual tool schema"),
  preconditions_met: z.boolean().optional().describe("Trusted host fact: prerequisites for this call are satisfied"),
  failed_attempts: z.number().int().nonnegative().optional().describe("Consecutive failures of this exact call; two failures block an unchanged retry"),
});

export const toolRouteInputSchema = z.object({
  task: z.string().min(1),
  observation: z.string(),
  candidates: z.array(toolCandidateSchema).max(32).describe("Up to 32 host-prepared calls. Empty or ineligible lists need no Jev request. Filter larger lists first."),
  auto_accept: z.number().min(0).max(1).optional(),
  review_at: z.number().min(0).max(1).optional(),
  model: z.string().optional(),
}).superRefine((input, context) => {
  const seen = new Set<string>();
  input.candidates.forEach((candidate, index) => {
    if (seen.has(candidate.id)) context.addIssue({ code: "custom", path: ["candidates", index, "id"], message: "Candidate IDs must be unique" });
    seen.add(candidate.id);
  });
});

export type ToolRouteInput = z.infer<typeof toolRouteInputSchema>;
export type ToolCandidate = z.infer<typeof toolCandidateSchema>;
type Candidate = ToolCandidate;
export const probability = z.number().min(0).max(1);
export const reasonSchema = z.enum([
  "accepted", "no_candidates", "no_eligible_candidates", "not_authorized", "arguments_not_validated",
  "preconditions_not_met", "retry_budget_exhausted", "unknown_effect", "no_suitable_call",
  "selection_uncertain", "suitability_uncertain", "incomplete_context", "effect_requires_review",
]);
export type Reason = z.infer<typeof reasonSchema>;
export const usageSchema = z.object({ input_tokens: z.number().nonnegative(), output_tokens: z.number().nonnegative() });
export const coverageSchema = z.object({
  complete: z.boolean(), original_chars: z.number().int().nonnegative(), evaluated_chars: z.number().int().nonnegative(),
  estimated_tokens: z.object({ state: z.number().int().nonnegative(), questions: z.number().int().nonnegative(), longest_question: z.number().int().nonnegative() }),
  estimator: z.literal("chars/4"),
});
export const toolRouteOutputSchema = z.object({
  model: z.string(),
  usage: usageSchema,
  truncated: z.boolean(),
  coverage: coverageSchema,
  action: z.enum(["auto", "review", "escalate"]),
  handoff: z.enum(["execute_tool", "gather_context", "review"]),
  partner_model: z.object({ required: z.literal(false), tier: z.literal("none") }),
  call: z.object({ candidate_id: z.string(), name: z.string(), arguments: argumentsSchema }).nullable(),
  selection: z.object({ id: z.string().nullable(), confidence: probability, suitability: probability.nullable() }).nullable(),
  blocked_candidates: z.array(z.object({ id: z.string(), reason_codes: z.array(reasonSchema).min(1) })),
  reason_codes: z.array(reasonSchema).min(1),
  thresholds: z.object({ auto_accept: probability, review_at: probability }),
});

/** Local eligibility from trusted host facts; shared with the fused step router. */
export function ineligibility(candidate: Candidate): Reason[] {
  const reasons: Reason[] = [];
  if (candidate.authorized !== true) reasons.push("not_authorized");
  if (candidate.schema_valid !== true) reasons.push("arguments_not_validated");
  if (candidate.preconditions_met !== true) reasons.push("preconditions_not_met");
  if ((candidate.failed_attempts ?? 0) >= 2) reasons.push("retry_budget_exhausted");
  if (candidate.effect === "unknown") reasons.push("unknown_effect");
  return reasons;
}

export async function runToolRoute(rawInput: ToolRouteInput, context?: ToolContext) {
  return withToolContext(context, async scoped => {
    const parsed = toolRouteInputSchema.safeParse(rawInput);
    if (!parsed.success) throw new JevValidationError(parsed.error.message);
    const input = parsed.data;
    const config = getConfig();
    const autoAccept = input.auto_accept ?? config.autoAccept;
    const reviewAt = input.review_at ?? config.reviewAt;
    validatePolicyThresholds(autoAccept, reviewAt);
    // Routing executable calls has a fixed safety floor, even with permissive judgment thresholds.
    const dispatchAt = Math.max(0.8, autoAccept);
    const blocked: Array<{ id: string; reason_codes: Reason[] }> = [];
    const candidates = input.candidates.filter(candidate => {
      const reasons = ineligibility(candidate);
      if (reasons.length) blocked.push({ id: candidate.id, reason_codes: reasons });
      return reasons.length === 0;
    });
    const shared = {
      partner_model: { required: false as const, tier: "none" as const },
      blocked_candidates: blocked,
      thresholds: { auto_accept: dispatchAt, review_at: reviewAt },
    };
    if (!candidates.length) {
      // No semantic choice exists: no provider call and no fabricated confidence.
      const coverage = {
        complete: true, original_chars: 0, evaluated_chars: 0,
        estimated_tokens: { state: 0, questions: 0, longest_question: 0 }, estimator: "chars/4" as const,
      };
      return toolRouteOutputSchema.parse({
        ...shared, model: "local-policy", usage: { input_tokens: 0, output_tokens: 0 },
        truncated: false, coverage, action: "review", handoff: blocked.length ? "review" : "gather_context",
        call: null, selection: null, reason_codes: [input.candidates.length ? "no_eligible_candidates" : "no_candidates"],
      });
    }
    const result = await systemOne({
      state: { task: input.task, observation: input.observation, candidates },
      questions: toolRouteQuestions(candidates.length), model: input.model,
    }, scoped);
    const selected = asChoice(result.answers.selected);
    const index = candidates.findIndex((_candidate, i) => selected.choice === `call_${i}`);
    const candidate = candidates[index];
    const suitability = candidate ? asNoul(result.answers[`suitable_${index}`]).noul : null;
    const reasons: Reason[] = [];
    const incomplete = result.truncated || !result.coverage.complete;
    if (incomplete) reasons.push("incomplete_context");
    if (selected.confidence < dispatchAt || !distributionSupportsConfidence(selected.probabilities, dispatchAt)) reasons.push("selection_uncertain");
    if (!candidate) reasons.push("no_suitable_call");
    if (suitability !== null && suitability < dispatchAt) reasons.push("suitability_uncertain");
    const needsReview = candidate?.effect === "external_write" || candidate?.effect === "destructive";
    if (needsReview) reasons.push("effect_requires_review");
    let action: PolicyAction = reasons.length ? "review" : "auto";
    if (selected.confidence < reviewAt || (suitability !== null && suitability < reviewAt)) action = "escalate";
    const call = action === "auto" && candidate
      ? { candidate_id: candidate.id, name: candidate.name, arguments: candidate.arguments }
      : null;
    return toolRouteOutputSchema.parse({
      ...shared, model: result.model, usage: result.usage, truncated: result.truncated, coverage: result.coverage,
      action, handoff: call ? "execute_tool" : needsReview ? "review" : "gather_context", call,
      selection: { id: candidate?.id ?? null, confidence: selected.confidence, suitability },
      reason_codes: reasons.length ? reasons : ["accepted"],
    });
  });
}
